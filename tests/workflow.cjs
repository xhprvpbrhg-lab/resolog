// Run with: NODE_PATH=/path/to/jsdom/node_modules node tests/workflow.cjs
const {JSDOM,VirtualConsole}=require('jsdom');
const fs=require('fs'),assert=require('node:assert/strict');
const errors=[];const vc=new VirtualConsole();vc.on('jsdomError',e=>errors.push(e.message));
let html=fs.readFileSync('index.html','utf8').replace('<script src="workflow.js"></script>','<script>'+fs.readFileSync('workflow.js','utf8')+'</script>');
const dom=new JSDOM(html,{runScripts:'dangerously',url:'https://example.test',virtualConsole:vc,beforeParse(w){w.scrollTo=()=>{};w.confirm=()=>true;w.URL.createObjectURL=()=> 'blob:test';w.URL.revokeObjectURL=()=>{};}});
const w=dom.window,d=w.document;
const run=code=>w.eval(code);
const input=(selector,value)=>{const e=d.querySelector(selector);assert.ok(e,selector);e.value=value;e.dispatchEvent(new w.Event('input',{bubbles:true}));};
const change=(selector,value)=>{const e=d.querySelector(selector);assert.ok(e,selector);e.value=value;e.dispatchEvent(new w.Event('change',{bubbles:true}));};
const click=selector=>{assert.ok(d.querySelector(selector),selector);d.querySelector(selector).click();};
assert.deepEqual(errors,[]);
run("clearForm(); document.querySelector('input[name=\"piano-type\"][value=\"grand\"]').checked=true;");
input('[data-pitch="pitchBefore"]','442.2');
change('[data-decision="pitch"]','unnecessary');
input('[data-measure="hammerClose"][data-zone="mid"]','1.7');
assert.equal(run('tuningData.pitchBefore'),'442.2');
assert.equal(run('checklist.action.hammerClose.mm.mid.before'),'1.7');
assert.equal(run('checklist.action.hammerClose.checked'),false);
input('[data-finding="eval.touch"]','Resistance at soft dynamics');
click('[data-plan="eval.touch"]');
click('[data-link="eval.evenness"]');
assert.equal(run('workflow.tasks.length'),1);
assert.equal(run('workflow.tasks[0].sources.length'),2);
click('[data-wf-phase="work"]');
change('[data-target-mode]','range');
click('[data-key="60"]');click('[data-key="72"]');
assert.equal(run('wfTarget(workflow.tasks[0].target)'),'C4–C5');
input('[data-task-memo]','Between string marks, shallow needling');
change('[data-task-status]','done');
run('performSave(false)');
assert.equal(run('records[0].workflow.tasks.length'),1);
assert.equal(run('buildSummaryItems(records[0]).filter(i=>i.id.startsWith("tuning.")).length'),0);
assert.equal(run('buildSummaryItems(records[0]).filter(i=>i.id.startsWith("task.")).length'),1);
run('populateFormForEdit(records[0])');
assert.equal(d.querySelector('[data-pitch]').value,'442.2');
assert.equal(d.querySelector('[data-measure="hammerClose"][data-zone="mid"]').value,'1.7');
click('[data-wf-phase="review"]');
input('[data-finding="eval.touch"]','More supple response');
assert.equal(run('evaluation.touch.memo'),'More supple response');
run('performSave(false);showDetail(records[0].id)');
assert.ok(d.querySelector('#view-detail').textContent.includes('Between string marks'));
run('window.exported=null;dlBlob=(blob,name)=>{window.exported={blob,name}};exportMD(records[0])');
assert.ok(w.exported.name.endsWith('.md'));
// Planned and deferred work never appear as completed summary work.
run("workflow.tasks[0].status='deferred';performSave(false)");
assert.equal(run('buildSummaryItems(records[0]).filter(i=>i.id.startsWith("task.")).length'),0);
// Legacy records retain old comments and measurement storage after editing.
run("window.old={id:'old',date:'2026-11-01',type:'grand',tuningData:{pitchBefore:'440',pitchAfter:'440'},checklist:{voicing:{shift:{checked:true,memo:'Legacy una corda'}}}};populateFormForEdit(window.old)");
assert.equal(run('checklist.voicing.shift.memo'),'Legacy una corda');
assert.ok(run('buildSummaryItems({...window.old,workflow}).some(i=>i.id==="tuning.pitch")'));
run("currentPianoType='upright';initChecklist();buildScenes()");
assert.ok(d.querySelector('#workflow-card'));
assert.equal(run('workflow.tasks.length'),0);
assert.deepEqual(errors,[]);
console.log('PASS: inspection decisions, shared measurements, task links, key ranges, completion filtering, save/edit, Markdown, legacy and upright');
dom.window.close();
